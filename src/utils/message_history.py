"""Bounded, authenticated-encrypted message history with guild-scoped storage."""

from dataclasses import dataclass, asdict, replace
import asyncio
from functools import wraps
import json
import logging
import os
from pathlib import Path
import stat
import tempfile
import time

import aiomysql
from cryptography.fernet import Fernet, InvalidToken

from src.utils.db import get_db_connection
from src.utils.message_logs import MessageSnapshot

logger = logging.getLogger(__name__)
MAX_VERSIONS = 10
MAX_SNAPSHOT_BYTES = 65536
EVENT_LABELS = {
    "created": "Message reçu", "imported": "Message importé", "captured": "Version précédente",
    "edited": "Message modifié", "deleted": "Message supprimé",
}


def retry_transaction(function):
    @wraps(function)
    async def wrapped(*args, **kwargs):
        for attempt in range(3):
            try:
                return await function(*args, **kwargs)
            except aiomysql.OperationalError as exc:
                if not exc.args or exc.args[0] not in {1205, 1213} or attempt == 2:
                    raise
                await asyncio.sleep(0.025 * 2 ** attempt)
    return wrapped


def serialize_records(function):
    @wraps(function)
    async def wrapped(self, guild_id, *args, **kwargs):
        # Preserve Gateway callback order without holding pooled connections
        # while other writes from the same guild are waiting.
        lock = self._record_locks.setdefault(guild_id, asyncio.Lock())
        async with lock:
            return await function(self, guild_id, *args, **kwargs)
    return wrapped


@dataclass(frozen=True)
class HistoryPolicy:
    enabled: bool = True
    retention_days: int = 30
    max_entries: int = 5000
    entry_count: int = 0
    configured: bool = False
    generation: int = 0


@dataclass(frozen=True)
class HistoryEntry:
    id: int
    guild_id: int
    channel_id: int
    message_id: int
    author_id: int | None
    event_kind: str
    recorded_at: int
    retention_started_at: int
    expires_at: int
    snapshot: MessageSnapshot
    unreadable: bool = False


@dataclass(frozen=True)
class HistoryResult:
    before: MessageSnapshot
    after: MessageSnapshot | None = None
    recorded: bool = False


def same_content(left: MessageSnapshot, right: MessageSnapshot) -> bool:
    def attachments(snapshot):
        return None if snapshot.attachments is None else tuple((item[0], item[1]) for item in snapshot.attachments)
    # Signed CDN URLs can change without an attachment being changed.
    return left.content == right.content and attachments(left) == attachments(right)


def merge_snapshot(primary: MessageSnapshot, fallback: MessageSnapshot) -> MessageSnapshot:
    return MessageSnapshot(**{
        key: value if value is not None else getattr(fallback, key)
        for key, value in asdict(primary).items()
    })


class HistoryCipher:
    def __init__(self, key: bytes):
        self._fernet = Fernet(key)

    @staticmethod
    def context(row):
        return [row[name] for name in (
            "guild_id", "channel_id", "message_id", "author_id", "event_kind", "recorded_at", "retention_started_at", "expires_at",
        )]

    def encrypt(self, snapshot: MessageSnapshot, row: dict) -> bytes:
        value = json.dumps({"context": self.context(row), "snapshot": asdict(snapshot)}, ensure_ascii=False).encode("utf-8")
        if len(value) > MAX_SNAPSHOT_BYTES:
            raise ValueError("Message snapshot exceeds the storage size limit")
        return self._fernet.encrypt(value)

    def decrypt(self, row: dict) -> MessageSnapshot:
        value = json.loads(self._fernet.decrypt(bytes(row["payload"])))
        if value["context"] != self.context(row):
            raise InvalidToken
        data = value["snapshot"]
        if data["attachments"] is not None:
            data["attachments"] = tuple(tuple(item) for item in data["attachments"])
        return MessageSnapshot(**data)


def load_key(path: Path, *, existing_history: bool) -> bytes:
    """Never replace a missing key while encrypted data still exists."""
    if not path.exists():
        if existing_history:
            raise RuntimeError("Message history key is missing. Restore the original key before starting the bot.")
        path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
        # Publish a complete key atomically. Concurrent initializers must never
        # observe an empty file or replace a key generated by another process.
        with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".content-key-", delete=False) as file:
            temporary = Path(file.name)
            try:
                file.write(Fernet.generate_key())
                file.flush()
                os.fsync(file.fileno())
                try:
                    os.link(temporary, path, follow_symlinks=False)
                except FileExistsError:
                    pass
            finally:
                temporary.unlink(missing_ok=True)
    descriptor = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
    with os.fdopen(descriptor, "rb") as file:
        info = os.fstat(file.fileno())
        if not stat.S_ISREG(info.st_mode) or info.st_mode & 0o077 or info.st_uid != os.getuid():
            raise RuntimeError("Message history key must be an owner-only regular file (mode 0600).")
        return file.read(128).strip()


async def initialize_history_store():
    db = await get_db_connection()
    try:
        async with db.cursor(aiomysql.DictCursor) as cursor:
            await cursor.execute("SELECT * FROM guild_message_history ORDER BY id DESC LIMIT 1")
            sample = await cursor.fetchone()
    finally:
        db.close()
    configured_key = os.getenv("MESSAGE_HISTORY_KEY")
    key = configured_key.encode("ascii") if configured_key else load_key(
        Path(os.getenv("MESSAGE_HISTORY_KEY_FILE", "history-keys/content.key")), existing_history=sample is not None,
    )
    try:
        cipher = HistoryCipher(key)
        if sample:
            cipher.decrypt(sample)
    except (ValueError, InvalidToken, KeyError, TypeError) as from_error:
        raise RuntimeError("Message history key is invalid or does not match existing data.") from from_error
    return HistoryStore(cipher)


class HistoryStore:
    def __init__(self, cipher: HistoryCipher):
        self.cipher = cipher
        self._record_locks: dict[int, asyncio.Lock] = {}

    async def _policy(self, cursor, guild_id: int, *, lock: bool = False) -> HistoryPolicy:
        await cursor.execute(
            "SELECT value FROM guild_config WHERE guild_id = %s AND config_key = 'logs_channel'", (guild_id,),
        )
        configured = bool(await cursor.fetchone())
        if lock:
            # A duplicate-key UPDATE takes an exclusive lock directly. INSERT
            # IGNORE followed by SELECT FOR UPDATE can deadlock during upgrades.
            await cursor.execute(
                "INSERT INTO guild_message_history_state (guild_id) VALUES (%s) "
                "ON DUPLICATE KEY UPDATE guild_id = %s", (guild_id, guild_id),
            )
        await cursor.execute(
            "SELECT enabled, retention_days, max_entries, entry_count, generation FROM guild_message_history_state "
            "WHERE guild_id = %s" + (" FOR UPDATE" if lock else ""), (guild_id,),
        )
        row = await cursor.fetchone()
        return HistoryPolicy(**row, configured=configured) if row else HistoryPolicy(configured=configured)

    async def policy(self, guild_id: int) -> HistoryPolicy:
        db = await get_db_connection()
        try:
            async with db.cursor(aiomysql.DictCursor) as cursor:
                return await self._policy(cursor, guild_id)
        finally:
            db.close()

    def entry(self, row) -> HistoryEntry:
        try:
            snapshot = self.cipher.decrypt(row)
            unreadable = False
        except (InvalidToken, ValueError, KeyError, TypeError):
            logger.error("Could not decrypt message history record id=%s", row["id"])
            snapshot, unreadable = MessageSnapshot(), True
        return HistoryEntry(**{key: row[key] for key in HistoryEntry.__dataclass_fields__ if key in row},
                            snapshot=snapshot, unreadable=unreadable)

    @serialize_records
    @retry_transaction
    async def record(self, guild_id: int, channel_id: int, message_id: int, kind: str,
                     snapshot: MessageSnapshot | None = None, *, update: dict | None = None,
                     source_created_at: int | None = None, now: int | None = None,
                     expected_generation: int | None = None) -> HistoryResult:
        if kind not in EVENT_LABELS or kind == "captured":
            raise ValueError("Unsupported history event")
        now = int(time.time()) if now is None else now
        snapshot = snapshot or MessageSnapshot()
        result = HistoryResult(snapshot, MessageSnapshot.from_update(update, snapshot) if update is not None else None)
        if snapshot.automated is True or (result.after is not None and result.after.automated is True):
            return result
        db = await get_db_connection()
        try:
            await db.begin()
            async with db.cursor(aiomysql.DictCursor) as cursor:
                policy = await self._policy(cursor, guild_id, lock=True)
                if not policy.enabled or not policy.configured:
                    await db.rollback()
                    return result
                if expected_generation is not None and expected_generation != policy.generation:
                    await db.rollback()
                    return result
                await cursor.execute(
                    "SELECT * FROM guild_message_history WHERE guild_id = %s AND channel_id = %s "
                    "AND message_id = %s AND expires_at > %s AND retention_started_at > %s ORDER BY id DESC LIMIT 1",
                    (guild_id, channel_id, message_id, now, now - policy.retention_days * 86400),
                )
                row = await cursor.fetchone()
                previous = self.entry(row).snapshot if row else MessageSnapshot()
                before = merge_snapshot(snapshot, previous)
                after = MessageSnapshot.from_update(update, before) if update is not None else None
                result = HistoryResult(before, after)
                if not (after or before).is_human:
                    await db.rollback()
                    return result
                if row and (kind in {"created", "imported"} or row["event_kind"] == "deleted"):
                    await db.rollback()
                    return HistoryResult(before, before if kind == "edited" else None)
                if kind == "edited" and after is not None and same_content(before, after):
                    await db.rollback()
                    return result
                expiry = now + policy.retention_days * 86400
                if kind == "imported" and source_created_at is not None:
                    expiry = min(expiry, source_created_at + policy.retention_days * 86400)
                if expiry <= now:
                    await db.rollback()
                    return result
                versions = []
                if kind in {"edited", "deleted"} and (before.content is not None or before.attachments is not None):
                    if row is None or not same_content(previous, before):
                        versions.append(("captured", before))
                versions.append((kind, after if after is not None else before))
                # Encrypt before executing any INSERT; oversized payloads never enter MySQL.
                records = []
                for event_kind, value in versions:
                    metadata = dict(guild_id=guild_id, channel_id=channel_id, message_id=message_id,
                                    author_id=value.author_id, event_kind=event_kind, recorded_at=now,
                                    retention_started_at=source_created_at if kind == "imported" and source_created_at is not None else now,
                                    expires_at=expiry)
                    # Fernet tokens are ASCII; avoid driver-specific binary escaping.
                    records.append((*metadata.values(), self.cipher.encrypt(value, metadata).decode("ascii")))
                await cursor.executemany(
                    "INSERT INTO guild_message_history "
                    "(guild_id, channel_id, message_id, author_id, event_kind, recorded_at, retention_started_at, expires_at, payload) "
                    "VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)", records,
                )
                count = policy.entry_count + len(records)
                await cursor.execute(
                    "SELECT id FROM guild_message_history WHERE guild_id = %s AND message_id = %s "
                    "ORDER BY id DESC LIMIT 1 OFFSET %s", (guild_id, message_id, MAX_VERSIONS - 1),
                )
                cutoff = await cursor.fetchone()
                if cutoff:
                    await cursor.execute(
                        "DELETE FROM guild_message_history WHERE guild_id = %s AND message_id = %s AND id < %s",
                        (guild_id, message_id, cutoff["id"]),
                    )
                    count -= cursor.rowcount
                if count > policy.max_entries:
                    await cursor.execute(
                        "DELETE FROM guild_message_history WHERE guild_id = %s ORDER BY id LIMIT %s",
                        (guild_id, count - policy.max_entries),
                    )
                    count -= cursor.rowcount
                await cursor.execute(
                    "UPDATE guild_message_history_state SET entry_count = %s WHERE guild_id = %s", (count, guild_id),
                )
            await db.commit()
            return HistoryResult(before, after, True)
        except Exception:
            await db.rollback()
            raise
        finally:
            db.close()

    async def records(self, guild_id: int, channel_id: int, *, message_id: int | None = None,
                      author_id: int | None = None, event_kind: str | None = None,
                      offset: int = 0, limit: int = 6, record_id: int | None = None) -> list[HistoryEntry]:
        if not 0 <= offset <= 20000 or not 1 <= limit <= MAX_VERSIONS:
            raise ValueError("History page exceeds its bounds")
        clauses = ["guild_id = %s", "channel_id = %s", "expires_at > %s"]
        params = [guild_id, channel_id, int(time.time())]
        for name, value in (("message_id", message_id), ("author_id", author_id),
                            ("event_kind", event_kind), ("id", record_id)):
            if name == "event_kind" and value == "changes":
                clauses.append("event_kind IN ('edited', 'deleted')")
            elif value is not None:
                clauses.append(f"{name} = %s")
                params.append(value)
        db = await get_db_connection()
        try:
            async with db.cursor(aiomysql.DictCursor) as cursor:
                policy = await self._policy(cursor, guild_id)
                if not policy.enabled or not policy.configured:
                    return []
                clauses.append("retention_started_at > %s")
                params.append(int(time.time()) - policy.retention_days * 86400)
                await cursor.execute(
                    f"SELECT * FROM guild_message_history WHERE {' AND '.join(clauses)} ORDER BY id DESC LIMIT %s OFFSET %s",
                    (*params, limit, offset),
                )
                return [replace(self.entry(row), expires_at=min(row["expires_at"], row["retention_started_at"] + policy.retention_days * 86400))
                        for row in await cursor.fetchall()]
        finally:
            db.close()

    @retry_transaction
    async def configure(self, guild_id: int, *, enabled: bool | None = None,
                        retention_days: int | None = None, max_entries: int | None = None):
        if retention_days is not None and not 1 <= retention_days <= 30:
            raise ValueError("Retention must be between 1 and 30 days")
        if max_entries is not None and not 100 <= max_entries <= 20000:
            raise ValueError("History capacity must be between 100 and 20000 versions")
        db = await get_db_connection()
        try:
            await db.begin()
            async with db.cursor(aiomysql.DictCursor) as cursor:
                policy = await self._policy(cursor, guild_id, lock=True)
                await cursor.execute(
                    "UPDATE guild_message_history_state SET enabled = %s, retention_days = %s, max_entries = %s, "
                    "generation = generation + 1 "
                    "WHERE guild_id = %s",
                    (policy.enabled if enabled is None else enabled,
                     policy.retention_days if retention_days is None else retention_days,
                     policy.max_entries if max_entries is None else max_entries, guild_id),
                )
                if enabled is False:
                    await cursor.execute("DELETE FROM guild_message_history WHERE guild_id = %s", (guild_id,))
                    await cursor.execute("UPDATE guild_message_history_state SET entry_count = 0 WHERE guild_id = %s", (guild_id,))
            await db.commit()
        except Exception:
            await db.rollback()
            raise
        finally:
            db.close()
        await self.cleanup(guild_id)

    async def known_guilds(self) -> set[int]:
        db = await get_db_connection()
        try:
            async with db.cursor() as cursor:
                await cursor.execute("SELECT guild_id FROM guild_message_history_state")
                return {row[0] for row in await cursor.fetchall()}
        finally:
            db.close()

    @retry_transaction
    async def cleanup(self, guild_id: int, *, now: int | None = None, active: bool = True):
        now = int(time.time()) if now is None else now
        db = await get_db_connection()
        try:
            await db.begin()
            async with db.cursor(aiomysql.DictCursor) as cursor:
                policy = await self._policy(cursor, guild_id, lock=True)
                # Do not modify authenticated expiry metadata when retention is reduced.
                await cursor.execute(
                    "DELETE FROM guild_message_history WHERE guild_id = %s "
                    "AND (expires_at <= %s OR retention_started_at <= %s OR %s = FALSE OR %s = FALSE OR %s = FALSE)",
                    (guild_id, now, now - policy.retention_days * 86400, policy.enabled, policy.configured, active),
                )
                await cursor.execute("SELECT COUNT(*) AS total FROM guild_message_history WHERE guild_id = %s", (guild_id,))
                count = (await cursor.fetchone())["total"]
                if count > policy.max_entries:
                    await cursor.execute(
                        "DELETE FROM guild_message_history WHERE guild_id = %s ORDER BY id LIMIT %s",
                        (guild_id, count - policy.max_entries),
                    )
                    count -= cursor.rowcount
                await cursor.execute("UPDATE guild_message_history_state SET entry_count = %s WHERE guild_id = %s", (count, guild_id))
            await db.commit()
        except Exception:
            await db.rollback()
            raise
        finally:
            db.close()

    @retry_transaction
    async def purge(self, guild_id: int, channel_id: int, *, message_id: int | None = None) -> int:
        db = await get_db_connection()
        try:
            await db.begin()
            async with db.cursor(aiomysql.DictCursor) as cursor:
                await self._policy(cursor, guild_id, lock=True)
                await cursor.execute(
                    "DELETE FROM guild_message_history WHERE guild_id = %s AND channel_id = %s" +
                    (" AND message_id = %s" if message_id is not None else ""),
                    (guild_id, channel_id, message_id) if message_id is not None else (guild_id, channel_id),
                )
                count = cursor.rowcount
                await cursor.execute(
                    "UPDATE guild_message_history_state SET entry_count = GREATEST(0, entry_count - %s), "
                    "generation = generation + 1 WHERE guild_id = %s",
                    (count, guild_id),
                )
            await db.commit()
            return count
        except Exception:
            await db.rollback()
            raise
        finally:
            db.close()
