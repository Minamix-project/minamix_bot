CREATE TABLE guild_reminders (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    guild_id BIGINT UNSIGNED NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    channel_id BIGINT UNSIGNED NULL,
    due_at BIGINT NOT NULL,
    message VARCHAR(1000) NOT NULL,
    category VARCHAR(32) NOT NULL DEFAULT 'custom',
    mention_owner BOOLEAN NOT NULL DEFAULT TRUE,
    recipient_ids JSON NOT NULL,
    status ENUM('pending', 'sending', 'sent', 'failed') NOT NULL DEFAULT 'pending',
    attempts INT UNSIGNED NOT NULL DEFAULT 0,
    revision INT UNSIGNED NOT NULL DEFAULT 0,
    next_attempt_at BIGINT NOT NULL DEFAULT 0,
    claim_token CHAR(32) NULL,
    claimed_until BIGINT NOT NULL DEFAULT 0,
    last_error VARCHAR(255) NULL,
    finished_at BIGINT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY idx_reminder_claim (claim_token),
    INDEX idx_reminder_due (status, due_at, next_attempt_at),
    INDEX idx_reminder_owner (guild_id, user_id, status, due_at),
    INDEX idx_reminder_cleanup (status, finished_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
